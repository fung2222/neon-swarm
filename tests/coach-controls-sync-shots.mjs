/**
 * COACH-CONTROLS-SYNC-001 screenshots (v0.9.78) — force coach visible; assert copy.
 */
import http from 'http';
import { createReadStream, existsSync, statSync, mkdirSync, writeFileSync } from 'fs';
import { join, extname, dirname } from 'path';
import { fileURLToPath } from 'url';
import puppeteer from 'puppeteer-core';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SHOT_DIR = join(ROOT, 'tests', 'screenshots', 'coach-controls-sync');
mkdirSync(SHOT_DIR, { recursive: true });
const CHROME = process.env.CHROME_PATH
  || (existsSync('/usr/bin/google-chrome-stable') ? '/usr/bin/google-chrome-stable' : '/usr/bin/google-chrome');
const VER = '0.9.78';
const WAIT = { timeout: 45000, polling: 250 };
const MIME = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.json': 'application/json', '.png': 'image/png', '.svg': 'application/svg+xml', '.woff2': 'font/woff2',
};

function startServer() {
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      const url = decodeURIComponent((req.url || '/').split('?')[0]);
      let rel = url === '/' ? '/index.html' : url;
      const file = join(ROOT, rel.replace(/^\//, ''));
      if (!file.startsWith(ROOT) || !existsSync(file) || statSync(file).isDirectory()) {
        res.writeHead(404); res.end('not found'); return;
      }
      res.writeHead(200, { 'Content-Type': MIME[extname(file)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
      createReadStream(file).pipe(res);
    });
    server.listen(0, '127.0.0.1', () => resolve({ server, base: `http://127.0.0.1:${server.address().port}` }));
  });
}

async function main() {
  const { server, base } = await startServer();
  const browser = await puppeteer.launch({
    executablePath: CHROME, headless: 'new',
    args: ['--no-sandbox', '--disable-setuid-sandbox', '--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader-webgl', '--ignore-gpu-blocklist', '--window-size=390,844'],
  });
  const page = await browser.newPage();
  await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const errs = [];
  page.on('pageerror', (e) => errs.push(String(e && e.message ? e.message : e)));
  await page.goto(base + `/index.html?v=${VER}&lang=zh`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForFunction(() => window.__swarm && window.__swarm.state === 'menu', WAIT);
  // Clear coach seen flag so a fresh run shows coach
  await page.evaluate(() => { try { localStorage.removeItem('neon-swarm-coach-v1'); } catch (_) {} });
  await page.click('#btn-play');
  await page.waitForFunction(() => window.__swarm && window.__swarm.state === 'play' && window.__swarm.game, WAIT);
  await new Promise((r) => setTimeout(r, 500));

  const probe = await page.evaluate(() => {
    const el = document.getElementById('run-coach');
    const zh = document.getElementById('run-coach-zh') || (el && el.querySelector('.coach-zh, [data-coach-zh], .zh'));
    const text = el ? el.textContent : '';
    return {
      hidden: !el || el.classList.contains('hidden'),
      text: (text || '').trim().slice(0, 200),
      hasDbl: /雙擊|DBL/i.test(text || ''),
      hasTpl: /三擊|TPL/i.test(text || ''),
      hasRail: /底欄|RAIL/i.test(text || ''),
    };
  });
  await page.screenshot({ path: join(SHOT_DIR, '01-phone-coach-controls.png'), type: 'png' });

  const fail = [];
  if (probe.hidden) fail.push('coach-hidden');
  if (!probe.hasDbl) fail.push('no-dbl');
  if (!probe.hasTpl) fail.push('no-tpl');
  if (!probe.hasRail) fail.push('no-rail');
  if (errs.length) fail.push(...errs.slice(0, 3).map((e) => 'pageerror:' + e));
  writeFileSync(join(SHOT_DIR, 'meta.json'), JSON.stringify({ ver: VER, probe, fail }, null, 2));
  await browser.close(); server.close();
  if (fail.length) { console.error('FAIL', fail, probe); process.exit(1); }
  console.log('coach-controls-sync-shots.mjs: PASS', probe);
}
main().catch((e) => { console.error(e); process.exit(1); });
